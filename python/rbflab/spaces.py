from .kernels import ScalarKernel,PHS,Hybrid,resolve_polynomial_degree


@dataclass(frozen=True)
class ScalarSpace:
    """Scalar radial approximation space with optional polynomials.

    Args:
        kernel: Scalar radial kernel or bound symbolic kernel.
        polynomial_degree: Degree, `None`, or `"auto"` for the kernel minimum."""
    kernel: object
    polynomial_degree: object = None

    def representers(self, source):
        """Construct trial functions by applying source functionals to the kernel.

        Value samples give ordinary kernel translates. Derivative samples
        give the corresponding source-argument derivatives. The same sample
        groups can be fitted to obtain Hermite interpolation.
        """
        from .samples import KernelTrial
        return KernelTrial(self, source)

    def translates(self, points):
        """Construct ordinary kernel translates at explicit trial centers."""
        from .samples import KernelTrial
        return KernelTrial(self, points, 'translates')

    def degree(self):
        if not isinstance(self.kernel,(ScalarKernel,PHS,Hybrid,BoundKernel)):raise TypeError("Expected a scalar radial kernel")
        minimum=getattr(self.kernel,'minimum_degree',-1)
        if isinstance(self,DivergenceFreeSpace):minimum=max(-1,minimum-1)
        degree=resolve_polynomial_degree(self.kernel,self.polynomial_degree,minimum_degree=minimum)
        order=6 if isinstance(self,DivergenceFreeSpace) else 2
        phs=self.kernel.phs if isinstance(self.kernel,Hybrid) else self.kernel if isinstance(self.kernel,PHS) else None
        if phs and phs.power-1<order:raise ValueError(f"This space requires continuous kernel derivatives through order {order}")
        return degree


@dataclass(frozen=True)
class DivergenceFreeSpace(ScalarSpace):
    """Velocity space generated by (Hessian - I*Laplacian) of phi.

    Every kernel column has zero analytic divergence. Polynomial columns
    are restricted to a solenoidal nullspace. The space changes the trial
    basis; it is not an extra discrete divergence constraint.
    """


@dataclass(frozen=True)
class PressureSpace(ScalarSpace):
    """Pressure modulo additive constants.

    This space omits an independent constant polynomial or gauge row.
    In LocalApproximation, source, trial and target functionals must
    annihilate constants. Use ScalarSpace for absolute pressure observations
    or evaluation and impose any global reference in the assembled equations.
    Specialized Stokes methods retain their documented pressure output rules.
    """


@dataclass(frozen=True)
class MixedSpace:
    """Named direct sum of scalar and divergence-free approximation spaces.

    Field names describe layout only, not PDE roles. Mixed local construction
    currently uses matching Hermite representers with explicit FieldOperator
    samples. A scalar factor retains its constant. A quotient PressureSpace
    factor omits constant polynomials and only admits observations and targets
    that annihilate its additive constant.
    """
    spaces: object

    @property
    def fields(self):
        """Original symbolic fields, or named expressions for string-keyed spaces."""
        from .field_expressions import FieldExpression
        return tuple(FieldExpression('field', (name,), isinstance(self.spaces[name], DivergenceFreeSpace))
                     if isinstance(key, str) else key for key, name in self._field_names)

    @property
    def field_spaces(self):
        """Field-to-space mapping retaining the user's original declaration keys."""
        return {key: self.spaces[name] for key, name in self._field_names}

    def __post_init__(self):
        from collections.abc import Mapping
        import copy
        if not isinstance(self.spaces, Mapping) or not self.spaces:
            raise ValueError('MixedSpace requires a nonempty field-to-space mapping')
        fields, names, atoms = {}, [], set()
        for key, space in self.spaces.items():
            if isinstance(key, str):
                if not key:
                    raise ValueError('Field names must be nonempty strings')
                name = key
            else:
                components = tuple(key) if isinstance(key, sp.MatrixBase) else (key,)
                if (not components or any(not isinstance(c, AppliedUndef) for c in components)
                        or (isinstance(key, sp.MatrixBase) and key.cols != 1)):
                    raise TypeError('MixedSpace keys must be names or declared symbolic fields')
                if atoms.intersection(components) or len(set(components)) != len(components):
                    raise ValueError('Symbolic field components must be distinct')
                atoms.update(components)
                name = str(components[0].func)
                if isinstance(key, sp.MatrixBase):
                    name = name.rsplit('_', 1)[0] if name.endswith('_0') else f'field_{len(names)}'
                if isinstance(key, sp.MatrixBase) != isinstance(space, DivergenceFreeSpace):
                    raise ValueError('Symbolic field shape must match its scalar or vector space')
                if any(c.args != components[0].args for c in components):
                    raise ValueError('Field components must share coordinates')
            if name in fields:
                raise ValueError(f'Duplicate normalized field name: {name}')
            if not isinstance(space, ScalarSpace):
                raise TypeError('Mixed fields require ScalarSpace or DivergenceFreeSpace')
            space.degree()
            fields[name] = copy.deepcopy(space)
            names.append((key, name))
        object.__setattr__(self, 'spaces', fields)
        object.__setattr__(self, '_field_names', tuple(names))

    def _symbolic_operator(self, expression, dimension):
        """Compile a constant-coefficient spatial functional of declared fields."""
        from .mixed import FieldOperator
        from .operators import Operator
        declared, coordinates = {}, None
        for key, name in self._field_names:
            if isinstance(key, str):
                continue
            components = tuple(key) if isinstance(key, sp.MatrixBase) else (key,)
            spatial = tuple(arg for arg in components[0].args if getattr(arg, 'name', None) != 't')
            if len(spatial) != dimension or any(not isinstance(x, sp.Symbol) for x in spatial):
                raise ValueError('Symbolic field and geometry dimensions must agree')
            if coordinates is not None and coordinates != spatial:
                raise ValueError('Symbolic fields must share spatial coordinates')
            coordinates = spatial
            if isinstance(key, sp.MatrixBase) and len(components) != dimension:
                raise ValueError('Vector field dimension must match geometry')
            for i, component in enumerate(components):
                declared[component] = (name, i, len(components))
        if not declared:
            raise ValueError('Symbolic observations require symbolic keys in MixedSpace')
        values = tuple(expression) if isinstance(expression, sp.MatrixBase) else (expression,)
        blocks = {}
        for row, value in enumerate(values):
            value = sp.expand(value.doit())
            if value.atoms(AppliedUndef) - set(declared):
                raise ValueError('Local expression contains undeclared fields')
            derivatives = tuple(sorted(value.atoms(sp.Derivative), key=sp.default_sort_key))
            slots = tuple(declared) + derivatives
            placeholders = tuple(sp.Dummy() for _ in slots)
            replaced = value.xreplace(dict(zip(slots, placeholders)))
            coefficients = [sp.diff(replaced, z) for z in placeholders]
            if any(c.has(*placeholders) for c in coefficients) or sp.simplify(replaced-sum(c*z for c,z in zip(coefficients,placeholders))) != 0:
                raise ValueError('Local observations must be homogeneous linear spatial functionals')
            for slot, coefficient in zip(slots, coefficients):
                if coefficient == 0:
                    continue
                alpha = [0]*dimension
                base = slot
                if isinstance(slot, sp.Derivative):
                    base = slot.expr
                    if base not in declared:
                        raise ValueError('Unsupported local field derivative')
                    for variable, order in slot.variable_count:
                        if variable not in coordinates:
                            raise ValueError('Local observations support spatial derivatives only')
                        alpha[coordinates.index(variable)] += int(order)
                name, component, width = declared[base]
                block = blocks.setdefault(name, [[0]*width for _ in values])
                block[row][component] = block[row][component] + Operator(((tuple(alpha), coefficient),), dimension)
        if not blocks:
            # Keep a valid input layout for an identically zero functional.
            name, _, width = next(iter(declared.values()))
            blocks[name] = [[0]*width for _ in values]
        return FieldOperator(blocks)

    def representers(self, source):
        """Apply whole mixed sample functionals to the block kernel."""
        from .samples import KernelTrial
        return KernelTrial(self, source)

    def translates(self, points):
        raise NotImplementedError('Mixed translates require an explicit field/component trial layout; use representers')


@dataclass(frozen=True)
class SpaceStokesProblem:
    """Compiled steady or transient momentum problem with field spaces.

    The problem stores viscosity, component forcing, boundary velocity,
    and optional initial velocity. Incompressibility is represented by
    the selected DivergenceFreeSpace, so there is no separate divergence
    equation or initial pressure datum.
    """
    model: object
    viscosity: object
    forcing: tuple
    boundary: tuple
    initial: object = None

    @property
    def dimension(self):return self.model.dimension
    @property
    def transient(self):return self.initial is not None
    def solve(self,cloud,method,**kwargs):return method.assemble(self,cloud).solve(**kwargs)


class SymbolicStokes:
    """Declare coupled velocity and pressure fields for Stokes momentum.

    Accepts one vector velocity and one scalar pressure in Cartesian 2D
    or 3D. Supply only the momentum vector equation: the selected
    DivergenceFreeSpace handles incompressibility. The general stationary
    SymbolicSystem branch remains available for other coupled PDEs.
    """
    def __init__(self,dimension=2,*,vector_fields=("U",),scalar_fields=("p",),transient=False):
        if vector_fields is None or scalar_fields is None or len(vector_fields)!=1 or len(scalar_fields)!=1:
            raise NotImplementedError("The vector space compiler currently accepts one velocity and one pressure field")
        names=tuple(vector_fields)+tuple(scalar_fields)
        if len(set(names))!=2 or any(not isinstance(n,str) or not n for n in names):raise ValueError("Expected distinct field names")
        self._scalar=SymbolicScalar(dimension,transient=transient)
        self.dimension=dimension;self.coordinates=self._scalar.coordinates;self.time=self._scalar.time
        self.normal=self._scalar.normal
        args=self.coordinates+((self.time,) if transient else ())
        self.velocity=sp.ImmutableMatrix([sp.Function(f'{names[0]}_{j}')(*args) for j in range(dimension)])
        self.pressure=sp.Function(names[1])(*args)
        self.fields=(self.velocity,self.pressure)

    def laplacian(self,expr):
        if isinstance(expr,sp.MatrixBase):return sp.ImmutableMatrix([self._scalar.laplacian(e) for e in expr])
        return self._scalar.laplacian(expr)
    def gradient(self,expr):return sp.ImmutableMatrix([sp.diff(expr,x) for x in self.coordinates])
    def divergence(self,expr):
        if len(expr)!=self.dimension:raise ValueError("Vector dimension mismatch")
        return sum(sp.diff(v,x) for v,x in zip(expr,self.coordinates))
    def bc(self,on,equation):return (on,equation)
    def data(self,expression,**kwargs):return self._scalar.data(expression,**kwargs)

    def stationary(self,equations,*,boundary,parameters=None):
        """Compile steady momentum rows and tagged velocity boundary data.

        Divergence is represented by the chosen velocity space, not by
        another symbolic equation. Returns SpaceStokesProblem.
        """
        if self.time is not None:raise ValueError("Use a non-transient model for stationary Stokes")
        return self._compile(equations,boundary,None,parameters)

    def evolution(self,equations,*,initial,boundary,parameters=None):
        """Compile unsteady momentum with initial velocity only.

        initial maps the declared velocity field to a vector expression.
        No initial pressure is required because pressure is a constraint
        variable, determined modulo its gauge.
        """
        if self.time is None:raise ValueError("Evolution requires transient=True")
        if not isinstance(initial,dict) or set(initial)!={self.velocity}:raise ValueError("Specify initial={velocity: vector_expression}; no initial pressure")
        return self._compile(equations,boundary,initial[self.velocity],parameters)

    def _compile(self,equations,boundary,initial,parameters):
        helper=self._scalar;mapping=helper._parameters(parameters)
        if isinstance(equations,sp.Equality):equations=[equations]
        rows=[]
        for eq in equations:
            expr=eq.lhs-eq.rhs if isinstance(eq,sp.Equality) else eq
            if isinstance(expr,sp.MatrixBase):rows.extend(expr)
            else:rows.append(_expr(expr))
        if len(rows)!=self.dimension:
            raise ValueError("Supply only the momentum vector equation; divergence is supplied by DivergenceFreeSpace")
        rows=[sp.expand(e.xreplace(mapping).doit()) for e in rows]
        nu=sp.simplify(-rows[0].coeff(sp.diff(self.velocity[0],self.coordinates[0],2)))
        _number(nu)
        if nu<=0:raise ValueError("Stokes viscosity must be a positive constant")
        forcing=[]
        for j,row in enumerate(rows):
            expected=-nu*self.laplacian(self.velocity[j])+sp.diff(self.pressure,self.coordinates[j])
            if initial is not None:expected+=sp.diff(self.velocity[j],self.time)
            rhs=sp.simplify(expected-row)
            if rhs.atoms(AppliedUndef) or rhs.has(sp.Derivative):
                raise NotImplementedError("Expected U_t - nu*Delta(U) + grad(p) = f (or steady form), with constant nu")
            forcing.append(helper._data(rhs,timed=initial is not None))
        bcs=[]
        for on,eq in boundary:
            if not isinstance(eq,sp.Equality) or eq.lhs!=self.velocity:
                raise NotImplementedError("Space Stokes currently supports prescribed velocity Eq(U, g) boundaries")
            if not isinstance(eq.rhs,sp.MatrixBase) or eq.rhs.shape!=(self.dimension,1):raise ValueError("Boundary velocity must be a column vector")
            bcs.append((on,tuple(helper._data(e.xreplace(mapping).doit(),timed=initial is not None) for e in eq.rhs)))
        init=None
        if initial is not None:
            initial=sp.ImmutableMatrix(initial).xreplace(mapping)
            if initial.shape!=(self.dimension,1):raise ValueError("Initial velocity dimension mismatch")
            if sp.simplify(self.divergence(initial))!=0:raise ValueError("Initial velocity must be divergence-free")
            init=tuple(helper._data(e.doit()) for e in initial)
        return SpaceStokesProblem(self,nu,tuple(forcing),tuple(bcs),init)
